"""Generate or check the flat index of long-lived Markdown under docs/."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from urllib.parse import quote

_INDEX = "documentation-index.md"


def _render(docs: Path) -> str:
    """Render stable, docs-relative links without timestamps or page counts."""
    pages = sorted(
        path.relative_to(docs).as_posix()
        for path in docs.rglob("*.md")
        if path.is_file()
        and not path.is_symlink()
        and path.name != "AGENTS.md"
        and path != docs / _INDEX
        and not any(part.startswith(".") for part in path.relative_to(docs).parts)
    )
    lines = [
        "---",
        "title: Documentation index",
        "type: documentation",
        "status: generated",
        "---",
        "",
        "# Documentation index",
        "",
        "<!-- Generated by code/scripts/docs_index.py; do not edit by hand. -->",
        "",
        "The [documentation hub](README.md) provides curated navigation. This flat",
        "index lists Markdown recursively under `docs/`, including manuscript,",
        "tools, and generated gate measurements. Agent instructions and this index",
        "are excluded. Regenerate from the repository root with",
        "`python code/scripts/docs_index.py --write .`; check with `--check .`.",
        "",
    ]
    for page in pages:
        label = page.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")
        lines.append(f"- [{label}]({quote(page, safe='/')})")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Check by default; write only the documentation index when requested."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", default=".", help="Repository root")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Exit 1 if the index is stale")
    mode.add_argument("--write", action="store_true", help="Regenerate the index")
    args = parser.parse_args(argv)
    docs = Path(args.root).resolve() / "docs"
    if not docs.is_dir():
        parser.error(f"documentation directory does not exist: {docs}")
    target = docs / _INDEX
    if target.is_symlink():
        parser.error(f"index must not be a symlink: {target}")
    expected = _render(docs)
    stale = not target.is_file() or target.read_text(encoding="utf-8") != expected
    if stale and args.write:
        target.write_text(expected, encoding="utf-8")
    if stale:
        print(f"docs/{_INDEX}")
    state = "regenerated" if stale and args.write else "stale" if stale else "current"
    print(f"documentation index {state}", file=sys.stderr)
    return int(stale and not args.write)


if __name__ == "__main__":
    raise SystemExit(main())
