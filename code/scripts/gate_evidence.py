"""Refresh or check the single generated document of local gate measurements."""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import re
import sys
from pathlib import Path
from typing import Any

DATA = Path("docs/development/gate-measurements.json")
DOCUMENT = DATA.with_suffix(".md")
SOURCES = [
    "run.sh",
    "pyproject.toml",
    "uv.lock",
    ".github/workflows/quality.yml",
    "code/scripts/gate.py",
    "code/scripts/docs_index.py",
    "code/scripts/gate_evidence.py",
    "code/scripts/build_manuscript.py",
    "code/scripts/validate_gnn_spec.py",
    "code/scripts/verify_links.py",
    "code/scripts/export_rdf.py",
    "code/scripts/mutation_check.py",
]


def source_hashes() -> dict[str, str]:
    return {name: hashlib.sha256(Path(name).read_bytes()).hexdigest() for name in SOURCES}


def measurement(path: Path) -> dict[str, Any]:
    records = json.loads(path.read_text())
    for arm, record in records.items():
        record["commands"] = [
            [
                "python"
                if index == 0 and "python" in argument
                else argument.replace(str(Path.cwd()), ".")
                for index, argument in enumerate(command)
            ]
            for command in record["commands"]
        ]
        log = path.parent / f"{path.stem}-{arm}.log"
        if log.exists() and arm in {"test", "test-full"}:
            text = log.read_text()
            passed = re.findall(r"(\d+) passed", text)
            coverage = re.findall(r"Total coverage: ([\d.]+)%", text)
            if passed:
                record["passed"] = int(passed[-1])
            if coverage:
                record["coverage_percent"] = float(coverage[-1])
    return records


def render(data: dict[str, Any]) -> str:
    before = data["before"]
    after = data["after"]
    lines = [
        "---",
        "title: Local gate measurements",
        "type: documentation",
        "status: generated",
        "---",
        "",
        "# Local gate measurements",
        "",
        "Generated by `python code/scripts/gate_evidence.py --refresh`; "
        "do not edit measured values.",
        "",
        f"Baseline source: `{data['baseline_revision']}`. "
        f"Host: {data['host']}; Python {data['python']}.",
        "",
        "One serial wall-time sample per arm per phase, using the same locked project environment.",
        "Dependency acquisition and supervisor admission are excluded. "
        "Warm caches are not cleared.",
        "The before fast-test sample reconstructs the same selected core-model",
        "commands against the original source; there was no named fast CI arm.",
        "The fast selection is not a substitute for full-suite coverage.",
        "Before manuscript: source generation and HTML; after uses the same selection.",
        "Single samples do not establish a general speedup. "
        "Hosted Actions did not verify these results.",
        "",
        *data.get("notes", []),
        "",
        "| Arm | Before (s) | Before exit | After (s) | After exit |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for name, value in before.items():
        final = after.get(name)
        seconds = f"{final['seconds']:.3f}" if final else "not measured"
        exit_code = str(final["exit_code"]) if final else "not measured"
        lines.append(
            f"| {name} | {value['seconds']:.3f} | {value['exit_code']} | {seconds} | {exit_code} |"
        )
    lines += [
        "",
        "## Test observations",
        "",
        "| Phase | Arm | Passed | Branch coverage (%) |",
        "| --- | --- | ---: | ---: |",
    ]
    for phase in ("before", "after"):
        for name, value in data[phase].items():
            if "passed" in value:
                lines.append(
                    f"| {phase} | {name} | {value['passed']} | "
                    f"{value.get('coverage_percent', 'not measured')} |"
                )
    lines += [
        "",
        "The adjacent JSON retains exact command selections, exit codes "
        "and gate-source SHA-256 bindings.",
        "Commands and refresh instructions: [development guide](README.md).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--refresh", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--before", type=Path)
    parser.add_argument("--after", type=Path)
    parser.add_argument("--baseline-revision")
    parser.add_argument("--baseline-note", action="append", default=[])
    args = parser.parse_args(argv)
    if args.refresh:
        if not args.before or not args.baseline_revision:
            parser.error("--refresh requires --before and --baseline-revision")
        data = {
            "schema": "cognitive-gate-measurements/v1",
            "baseline_revision": args.baseline_revision,
            "host": f"{platform.system()} {platform.release()} {platform.machine()}",
            "python": sys.version.split()[0],
            "sources": source_hashes(),
            "before": measurement(args.before),
            "after": measurement(args.after) if args.after else {},
            "notes": args.baseline_note,
        }
        DATA.write_text(json.dumps(data, indent=2) + "\n")
        DOCUMENT.write_text(render(data))
        return 0
    data = json.loads(DATA.read_text())
    if data["sources"] != source_hashes() or DOCUMENT.read_text() != render(data):
        print(
            "Gate evidence is stale: refresh from the preserved measurement records.",
            file=sys.stderr,
        )
        return 1
    print("Gate measurements match recorded evidence and source bindings.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
