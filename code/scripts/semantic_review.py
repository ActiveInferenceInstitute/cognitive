def _digest(value: object) -> str:
    return hashlib.sha256(
        json.dumps(value, ensure_ascii=False, sort_keys=True).encode()
    ).hexdigest()


def _json_metadata(value: Any) -> Any:
    """Retain YAML scalar types that JSON cannot represent directly."""
    if isinstance(value, (datetime, date)):
        return {
            "yaml_type": "datetime" if isinstance(value, datetime) else "date",
            "value": value.isoformat(),
        }
    if isinstance(value, list):
        return [_json_metadata(item) for item in value]
    if isinstance(value, dict):
        if any(not isinstance(key, str) for key in value):
            raise ValueError("review metadata requires string mapping keys")
        return {key: _json_metadata(item) for key, item in value.items()}
    if value is None or isinstance(value, (str, bool, int, float)):
        return value
    raise ValueError(f"unsupported source metadata type: {type(value).__name__}")


def _field(node: Node | None, key: str) -> Node | None:
    # WHY: SafeLoader keeps the last duplicate YAML key; use the same field here.
    values = (
        [v for k, v in node.value if isinstance(k, ScalarNode) and k.value == key]
        if isinstance(node, MappingNode)
        else []
    )
    return values[-1] if values else None


def _leaves(node: Node | None) -> list[Node]:
    if isinstance(node, SequenceNode):
        return [leaf for child in node.value for leaf in _leaves(child)]
    return [] if node is None else [node]


def _declarations(text: str, frontmatter: dict[str, Any]) -> list[dict[str, Any]]:
    """Attach YAML scalar origins to the exporter's own ordered relation parser.

    Marks identify scalar definitions, including definitions reused by YAML aliases.
    Entry/leaf indices retain every declaration use; no alias-use line is guessed.
    """
    match = _FRONTMATTER.match(text)
    node = yaml.compose(match[1]) if match else None
    relations_node = _field(node, "semantic_relations")
    entries = frontmatter.get("semantic_relations")
    if not isinstance(entries, list):
        return []
    entry_nodes = relations_node.value if isinstance(relations_node, SequenceNode) else []
    result = []
    for entry_index, entry in enumerate(entries):
        if not isinstance(entry, dict):
            continue
        entry_node = entry_nodes[entry_index] if entry_index < len(entry_nodes) else None
        for key in ("links", "parent"):
            # The authoritative parser handles defaults, nested lists and raw wiki syntax.
            subset = {"type": entry.get("type"), key: entry.get(key)}
            pairs = rdf.semantic_relations([subset])
            leaf_nodes = _leaves(_field(entry_node, key))
            values = rdf._flatten(entry.get(key))
            eligible = [
                (i, value, leaf_nodes[i] if i < len(leaf_nodes) else None)
                for i, value in enumerate(values)
                if rdf._link_target(value)
            ]
            if len(pairs) != len(eligible):
                raise ValueError("source declaration provenance differs from exporter parsing")
            for (relation, target), (leaf_index, raw, leaf) in zip(pairs, eligible, strict=True):
                context: dict[str, Any] = {
                    "entry_index": entry_index,
                    "field": key,
                    "leaf_index": leaf_index,
                    "relation": relation,
                    "parsed_target": target,
                    "raw_target": raw,
                    "location_kind": "yaml_scalar_origin",
                }
                if leaf is not None and match is not None:
                    offset = text[: match.start(1)].count("\n")
                    context["line"] = offset + leaf.start_mark.line + 1
                    # End marks are exclusive; a block scalar may end at column zero.
                    context["end_line"] = offset + leaf.end_mark.line + (leaf.end_mark.column > 0)
                    context["fragment"] = text.splitlines()[
                        context["line"] - 1 : context["end_line"]
                    ]
                result.append(context)
    return result


def _role(types: list[str], topic: bool, node: str, rdf_types: list[str]) -> str:
    """Explain observed RDF roles without deciding topic eligibility again."""
    if topic:
        return "Document describing a separate topic, as emitted through schema:about."
    if "citation" in types or "citation_redirect" in types or "citations" in node.split("/"):
        return "Publication/citation document role; the publication is not itself a topic."
    if rdf.PREFIXES["schema"] + "CollectionPage" in rdf_types:
        return "Navigation/collection document role; links organize documents."
    if set(types) & {"implementation", "implementation_guide", "guide", "learning_path"}:
        return "Guide or implementation document role; typed links do not establish a topic."
    return "Document-only RDF role under current policy; this does not establish a missing concept."


def _endpoint(root: Path, node: str, path: Path, index: GraphIndex) -> dict[str, Any]:
    subject = rdf.iri(rdf.page_iri(node))
    types = sorted(index.objects(subject, rdf.RDF_TYPE))
    topics = sorted(index.objects(subject, rdf.PREFIXES["schema"] + "about"))
    metadata = index.by_subject.get(subject, {})
    if rdf.iri(rdf.PREFIXES["schema"] + "CreativeWork") not in types:
        raise ValueError(f"route endpoint has no emitted document: {node}")
    sources = sorted(index.objects(subject, rdf.PREFIXES["dcterms"] + "source"))
    if len(sources) != 1 or not sources[0].startswith("<"):
        raise ValueError(f"route endpoint requires one emitted source URL: {node}")
    rdf._require_regular_source(path, root)
    source_bytes = path.read_bytes()
    fm, _ = rdf._split(source_bytes.decode("utf-8"))
    page_types = sorted(index.objects(subject, rdf.VOCAB + "pageType"))
    # The exporter emits pageType with rdf.literal(str(...)); keep the RDF terms too.
    source_types = [str(fm["type"]).strip()] if fm.get("type") else []
    if page_types != [rdf.literal(t) for t in source_types]:
        raise ValueError(f"source types changed after graph build: {node}")
    titles = sorted(index.objects(subject, rdf.PREFIXES["dcterms"] + "title"))
    # Use the exporter title function only for presentation; RDF terms stay exact.
    return {
        "path": path.relative_to(root).as_posix(),
        "document_iri": rdf.page_iri(node),
        "source_url": sources[0][1:-1],
        "source_sha256": hashlib.sha256(source_bytes).hexdigest(),
        "title": rdf._title(fm, node),
        "title_terms": titles,
        "source_types": source_types,
        "source_type_terms": page_types,
        "rdf_types": [term[1:-1] for term in types],
        "has_topic": bool(topics),
        "topic_iris": [term[1:-1] for term in topics],
        "role_explanation": _role(source_types, bool(topics), node, [t[1:-1] for t in types]),
        "source_metadata": {key: _json_metadata(fm[key]) for key in _METADATA_FIELDS if key in fm},
        "rdf_metadata": {p[1:-1]: sorted(values) for p, values in sorted(metadata.items())},
    }


def build_review_queue(root: Path) -> dict[str, Any]:
    """Build a deterministic queue from authoritative Graph and Report, without writes.

    Source assertion IDs retain exact labels/reasons. Effective IDs identify RDF
    source/predicate/target triples. Repeated declarations remain separate occurrences.
    Only Report.document_relation_routes are in scope, not all document-valued edges.
    """
    root = Path(root).absolute()
    _real_chain(root)
    root = root.resolve()
    hashes = rdf._source_hashes(root)
    inventory = rdf._resolution_files(root)
    graph, report = rdf.build_graph(root)
    index = GraphIndex.build(graph.triples)
    # Exact extension case comes from the source inventory, not an assumed .md suffix.
    paths = {
        p.relative_to(root / rdf.KB_NAME).with_suffix("").as_posix(): p
        for p in rdf._markdown_paths(root / rdf.KB_NAME)
    }
    endpoints = {
        n: _endpoint(root, n, paths[n], index)
        for n in sorted(
            {r[k] for r in report.document_relation_routes for k in ("source", "target")}
        )
    }
    link_index = rdf._shipped_index(root)
    contexts: dict[tuple[str, str, str], deque] = defaultdict(deque)
    for source in sorted({r["source"] for r in report.document_relation_routes}):
        path = root / endpoints[source]["path"]
        text = path.read_text(encoding="utf-8")
        fm, _ = rdf._split(text)
        for context in _declarations(text, fm):
            target = rdf._resolve(root, path, context["parsed_target"], link_index)
            if not target or target == source:
                continue
            url = endpoints[source]["source_url"]
            if "line" in context:
                url += f"#L{context['line']}"
                if context["end_line"] != context["line"]:
                    url += f"-L{context['end_line']}"
            context["source_url"] = url
            context["occurrence_id"] = "occurrence-" + _digest([source, context])
            contexts[source, context["relation"], target].append(context)

    rows: dict[tuple[str, ...], dict[str, Any]] = {}
    for route in report.document_relation_routes:
        source, relation, target, predicate, reason = (
            route[k] for k in ("source", "relation", "target", "predicate", "reason")
        )
        triple = (rdf.iri(rdf.page_iri(source)), rdf.iri(predicate), rdf.iri(rdf.page_iri(target)))
        if triple not in graph.triples:
            raise ValueError("route is absent from emitted RDF")
        key = source, relation, target, predicate, reason
        if key not in rows:
            rows[key] = {
                **route,
                "assertion_id": "assertion-" + _digest(key),
                "effective_assertion_id": "effective-" + _digest([source, predicate, target]),
                "direction": "source_to_target",
                "disposition": "unresolved_interpretation"
                if UNRESOLVED_REASON in reason
                else "ordinary_document_relation",
                "declarations": [],
            }
        available = contexts[source, relation, target]
        if not available:
            raise ValueError(
                f"route has no matching source declaration: {source} / {relation} / {target}"
            )
        rows[key]["declarations"].append(available.popleft())
    assertions = [rows[key] for key in sorted(rows)]
    for row in assertions:
        row["occurrence_count"] = len(row["declarations"])
    ambiguous = [r for r in assertions if r["disposition"] == "unresolved_interpretation"]
    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    unassigned = []
    for row in ambiguous:
        document_only = sorted(
            {row["source"], row["target"]} - {n for n in endpoints if endpoints[n]["has_topic"]}
        )
        if not document_only:
            unassigned.append(row["assertion_id"])
        for endpoint in document_only:
            groups[endpoint].append(row)
    grouped = []
    union: set[str] = set()
    for endpoint in sorted(groups, key=lambda n: (-len(groups[n]), n)):
        incident = groups[endpoint]
        ids = [r["assertion_id"] for r in incident]
        union.update(ids)
        grouped.append(
            {
                "endpoint": endpoint,
                "incident_assertion_count": len(ids),
                "assertion_ids": ids,
                "incident_effective_assertion_count": len(
                    {r["effective_assertion_id"] for r in incident}
                ),
                "declaration_occurrences": sum(r["occurrence_count"] for r in incident),
                "as_source": sum(r["source"] == endpoint for r in incident),
                "as_target": sum(r["target"] == endpoint for r in incident),
                "cumulative_distinct_union": len(union),
            }
        )
    ordinary_ids = [r["assertion_id"] for r in assertions if r not in ambiguous]
    ambiguous_ids = {r["assertion_id"] for r in ambiguous}
    if union & set(unassigned) or union | set(unassigned) != ambiguous_ids:
        raise ValueError("review queue coverage union does not match ambiguous assertions")
    if sum(r["occurrence_count"] for r in assertions) != report.document_relation_assertions:
        raise ValueError("review declaration accounting differs from exporter report")
    rdf._require_stable_sources(root, hashes)
    if rdf._resolution_files(root) != inventory:
        raise ValueError("resolution inputs changed during review build")
    return {
        "schema_version": 1,
        "generator": GENERATOR,
        "scope": (
            "Report.document_relation_routes only; omissions and other RDF routes "
            "remain outside this view."
        ),
        "export_omissions": {
            "unresolved_links": report.unresolved_links,
            "links_outside_graph": report.links_outside_graph,
            "self_loops_dropped": report.self_loops_dropped,
        },
        "counts": {
            "source_declaration_occurrences": len(report.document_relation_routes),
            "unique_source_assertions": len(assertions),
            "unique_effective_assertions": len({r["effective_assertion_id"] for r in assertions}),
            "ambiguous_declaration_occurrences": sum(r["occurrence_count"] for r in ambiguous),
            "ordinary_declaration_occurrences": sum(
                r["occurrence_count"] for r in assertions if r["assertion_id"] in ordinary_ids
            ),
            "ambiguous_distinct_union": len(ambiguous_ids),
            "ordinary_distinct_assertions": len(ordinary_ids),
            "grouped_distinct_union": len(union),
            "endpoint_groups": len(grouped),
            "group_memberships": sum(g["incident_assertion_count"] for g in grouped),
            "relation_policy_distinct_assertions": len(unassigned),
        },
        "endpoints": endpoints,
        "assertions": assertions,
        "endpoint_groups": grouped,
        "relation_policy_review": unassigned,
        "ordinary_document_relations": ordinary_ids,
    }


def _cell(value: object) -> str:
    return (
        str(value).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ").replace("\r", " ")
    )


def _link(label: str, url: str) -> str:
    label = _cell(label).replace("[", "\\[").replace("]", "\\]")
    return f"[{label}]({url.replace('(', '%28').replace(')', '%29')})"


def _source_literal(value: str) -> str:
    """Quote source examples as code so they do not become new wiki references."""
    text = value.replace("\n", "\\n").replace("\r", "\\r")
    fence = "`" * (max((len(run) for run in re.findall(r"`+", text)), default=0) + 1)
    return f"{fence} {text} {fence}"


def render_markdown(queue: dict[str, Any]) -> str:
    """Render all review groups, unassigned policy rows and ordinary routes."""
    counts = queue["counts"]
    endpoints = queue["endpoints"]
    rows = {r["assertion_id"]: r for r in queue["assertions"]}
    lines = [
        MARKDOWN_HEADER,
        "# Semantic relation review queue",
        "",
        "Source-authored assertions retain their current direction, predicates and reasons. "
        "This view proposes no mappings, definitions, confidence values or role changes.",
        "",
        "Counts distinguish declaration occurrences, unique source assertions "
        "(exact label and reason), "
        "and unique effective RDF triples. Repeated declarations are retained below; normalized "
        "labels can share an effective triple. Groups overlap, so coverage uses "
        "distinct assertion IDs.",
        "",
        "| Measure | Count |",
        "|---|---:|",
        *[f"| {_cell(k)} | {counts[k]} |" for k in sorted(counts)],
        "",
        "Scope: " + queue["scope"],
        "",
        "Exporter omission counters (not conceptual ambiguity): `"
        + json.dumps(queue["export_omissions"], sort_keys=True)
        + "`.",
        "",
        "## Document-only endpoint groups",
        "",
        "Citation, guide, implementation and navigation roles are deliberate document roles. "
        "An unresolved interpretation does not require promoting a document to a topic.",
        "",
        "| Endpoint | Source type | Incident assertions | As source | As target | "
        "Cumulative distinct union |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for group in queue["endpoint_groups"]:
        node = group["endpoint"]
        endpoint = endpoints[node]
        lines.append(
            f"| {_link(node, endpoint['source_url'])} | {_cell(endpoint['source_types'])} | "
            f"{group['incident_assertion_count']} | {group['as_source']} | "
            f"{group['as_target']} | {group['cumulative_distinct_union']} |"
        )

    def render_rows(ids: list[str]) -> None:
        lines.extend(
            [
                "",
                "| Assertion | Source → target (types; topic presence) | Exact relation | "
                "Predicate | Current reason | Occurrences |",
                "|---|---|---|---|---|---:|",
            ]
        )
        for assertion_id in ids:
            row = rows[assertion_id]
            source, target = (endpoints[row[k]] for k in ("source", "target"))
            ends = " → ".join(
                _link(row[k], ep["source_url"])
                + f" ({_cell(ep['source_types'])}; topic={ep['has_topic']})"
                for k, ep in (("source", source), ("target", target))
            )
            lines.append(
                f"| `{assertion_id}` | {ends} | {_cell(row['relation'])} | "
                f"{_cell(row['predicate'])} | {_cell(row['reason'])} | {row['occurrence_count']} |"
            )
        lines.extend(
            [
                "",
                "Source declaration context (YAML scalar origins; aliases may reuse an origin). "
                "Entry/leaf indices identify separate uses; line numbers do not guess "
                "alias-use locations.",
                "",
            ]
        )
        for assertion_id in ids:
            for declaration in rows[assertion_id]["declarations"]:
                lines.append(
                    f"- `{declaration['occurrence_id']}` for `{assertion_id}`: "
                    + _link("source", declaration["source_url"])
                    + f"; entry {declaration['entry_index']}, {declaration['field']} leaf "
                    f"{declaration['leaf_index']}; raw target: "
                    f"{_source_literal(declaration['raw_target'])}; "
                    f"parsed target: {_source_literal(declaration['parsed_target'])}."
                )

    for group in queue["endpoint_groups"]:
        node = group["endpoint"]
        lines.extend(["", f"### {_cell(node)}", "", endpoints[node]["role_explanation"]])
        render_rows(group["assertion_ids"])
    lines.extend(
        [
            "",
            "## Relation-policy review",
            "",
            "These unresolved assertions have two topic-bearing endpoints and therefore no "
            "document-only group. They remain in the distinct coverage union.",
        ]
    )
    render_rows(queue["relation_policy_review"])
    lines.extend(
        [
            "",
            "## Ordinary document relations",
            "",
            "These carry the router's documented meanings and do not require conceptual curation.",
        ]
    )
    render_rows(queue["ordinary_document_relations"])
    lines.extend(["", "## Endpoint source context", ""])
    for node, endpoint in endpoints.items():
        lines.extend(
            [
                f"### {_cell(node)}",
                "",
                _link(endpoint["title"], endpoint["source_url"]),
                "",
                endpoint["role_explanation"],
                "",
                f"Source types: {_cell(endpoint['source_types'])}; topic={endpoint['has_topic']}. "
                f"Source SHA-256: `{endpoint['source_sha256']}`.",
                "",
                "Source-declared metadata (typed dates retained; editorial values are "
                "not semantic confidence):",
                "",
                "```json",
                json.dumps(
                    endpoint["source_metadata"], ensure_ascii=False, indent=2, sort_keys=True
                ),
                "```",
                "",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def expected_outputs(queue: dict[str, Any]) -> dict[str, str]:
    """Return portable generated filenames and exact deterministic UTF-8 contents."""
    return {
        JSON_NAME: json.dumps(queue, ensure_ascii=False, indent=2, sort_keys=True, allow_nan=False)
        + "\n",
        MARKDOWN_NAME: render_markdown(queue),
    }


def _real_chain(path: Path) -> None:
    for part in reversed((path, *path.parents)):
        if part.is_symlink() or (part.exists() and not part.is_dir()):
            raise ValueError(f"directory must be real and without symlinks: {part}")


def _output_directory(root: Path, output: Path) -> Path:
    root = Path(root).absolute()
    _real_chain(root)
    output = Path(output)
    if ".." in output.parts:
        raise ValueError("output cannot escape through parent segments")
    output = output if output.is_absolute() else root / output
    if not output.is_relative_to(root):
        raise ValueError("output must remain within the chosen repository root")
    relative = output.relative_to(root)
    if relative.parts and (
        relative.parts[0] in {rdf.KB_NAME, "code"} or any(p.startswith(".") for p in relative.parts)
    ):
        raise ValueError("output cannot collide with source or hidden directories")
    _real_chain(output)
    return output


def _read_destination(path: Path) -> bytes | None:
    try:
        info = path.lstat()
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise ValueError(f"output collision: requires an unlinked regular file: {path.name}")
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(descriptor, "rb") as stream:
        if os.fstat(stream.fileno()) != info:
            raise ValueError("output changed during preflight")
        return stream.read()


def _owned(name: str, content: bytes) -> bool:
    if name == MARKDOWN_NAME:
        return content.startswith(MARKDOWN_HEADER.encode())
    try:
        value = json.loads(content)
        return (
            isinstance(value, dict)
            and value.get("generator") == GENERATOR
            and value.get("schema_version") == 1
        )
    except (ValueError, UnicodeError):
        return False


def stale_outputs(root: Path, output: Path, queue: dict[str, Any]) -> list[str]:
    """List missing/stale output files without creating directories or files."""
    directory = _output_directory(root, output)
    return [
        name
        for name, content in expected_outputs(queue).items()
        if _read_destination(directory / name) != content.encode("utf-8")
    ]


def write_outputs(root: Path, output: Path, queue: dict[str, Any]) -> None:
    """Explicitly write only the generated pair after preflighting both destinations.

    Existing unrelated files, symlinks, hardlinks and source directories are refused.
    Replacements are atomic per file; callers serialize concurrent queue writers.
    """
    directory = _output_directory(root, output)
    outputs = expected_outputs(queue)
    previous = {name: _read_destination(directory / name) for name in outputs}
    for name, prior_bytes in previous.items():
        if prior_bytes is not None and not _owned(name, prior_bytes):
            raise ValueError(f"output collision with unrelated content: {name}")
    # O_NOFOLLOW at every directory level also guards a swapped parent after preflight.
    descriptor = os.open(directory.anchor, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        for part in directory.parts[1:]:
            try:
                child = os.open(
                    part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=descriptor
                )
            except FileNotFoundError:
                os.mkdir(part, dir_fd=descriptor)
                child = os.open(
                    part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=descriptor
                )
            os.close(descriptor)
            descriptor = child
        for name, content in outputs.items():
            if _read_destination(directory / name) != previous[name]:
                raise ValueError("output changed after preflight")
            temporary = ".semantic-review-" + uuid.uuid4().hex
            handle = os.open(
                temporary,
                os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                0o644,
                dir_fd=descriptor,
            )
            try:
                with os.fdopen(handle, "wb") as stream:
                    stream.write(content.encode("utf-8"))
                    stream.flush()
                    os.fsync(stream.fileno())
                os.replace(temporary, name, src_dir_fd=descriptor, dst_dir_fd=descriptor)
            finally:
                # Successful replacement consumed the temporary file.
                with suppress(FileNotFoundError):
                    os.unlink(temporary, dir_fd=descriptor)
    finally:
        os.close(descriptor)


def main(argv: list[str] | None = None) -> int:
    """Print a read-only report, explicitly generate outputs, or check stale bytes."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=Path("."), help="repository root")
    parser.add_argument("--json", action="store_true", help="print machine-readable report")
    parser.add_argument(
        "--output", type=Path, help="contained output directory (explicit mode required)"
    )
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--write", action="store_true", help="generate the Markdown/JSON pair")
    modes.add_argument("--check", action="store_true", help="exit 1 on missing or stale output")
    args = parser.parse_args(argv)
    if bool(args.output) != bool(args.write or args.check):
        parser.error("--output requires --write or --check, and either mode requires --output")
    try:
        queue = build_review_queue(args.root)
        if args.check:
            stale = stale_outputs(args.root, args.output, queue)
            print(
                json.dumps({"stale": stale}, sort_keys=True)
                if args.json
                else "\n".join(stale)
                if stale
                else "Semantic review outputs are current"
            )
            return int(bool(stale))
        if args.write:
            write_outputs(args.root, args.output, queue)
        print(expected_outputs(queue)[JSON_NAME] if args.json else render_markdown(queue), end="")
        return 0
    except (OSError, ValueError, yaml.YAMLError) as error:
        print(f"semantic review: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
